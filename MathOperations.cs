// This class contains methods that perform different math operations.
public class MathOperations
{
    // This method takes an integer and returns the number multiplied by 2.
    public int MultiplyByTwo(int number)
    {
        return number * 2;
    }

    // This method takes an integer and returns the number plus 10.
    public int AddTen(int number)
    {
        return number + 10;
    }

    // This method takes an integer and returns the number squared.
    public int SquareNumber(int number)
    {
        return number * number;
    }
}